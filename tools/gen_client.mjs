#!/usr/bin/env node
// gen_client.mjs generates web/src/app/api/client.ts from api/openapi.yaml.
//
//   node tools/gen_client.mjs           write the client
//   node tools/gen_client.mjs --check   exit 1 if the committed client is stale
//
// The client lives in the app layer because the API carries domain names; web/src/kernel
// stays domain-free. YAML is parsed with the `yaml` devDependency of web/ (npm --prefix web
// install). Output is deterministic: schemas and operations are emitted in document order.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = join(root, "api/openapi.yaml");
const outPath = join(root, "web/src/app/api/client.ts");
const METHODS = ["get", "post", "put", "patch", "delete"];

// loadSpec parses api/openapi.yaml with the yaml package installed under web/.
export function loadSpec() {
  const { parse } = createRequire(join(root, "web/package.json"))("yaml");
  return parse(readFileSync(specPath, "utf8"), { maxAliasCount: -1 });
}

const refName = (ref) => ref.replace("#/components/schemas/", "");
const pascal = (s) => s.replace(/(^|[_.\s-])([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const prop = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k));

// tsType renders a schema as a TypeScript type. Extensible enums allow the "other"
// sentinel that decode() substitutes for unknown values (ARC-I-002).
function tsType(s, ind) {
  if (!s) return "unknown";
  if (s.$ref) return refName(s.$ref);
  if (s.enum) {
    const lits = s.enum.map((v) => JSON.stringify(v));
    if (s["x-extensible-enum"]) lits.push('"other"');
    return lits.join(" | ");
  }
  const types = Array.isArray(s.type) ? s.type : [s.type];
  const parts = types.map((t) => {
    switch (t) {
      case "string":
        return "string";
      case "integer":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array":
        return `Array<${tsType(s.items, ind)}>`;
      case "object":
        return s.properties ? objType(s, ind) : "Record<string, unknown>";
      default:
        return s.properties ? objType(s, ind) : "unknown";
    }
  });
  return parts.join(" | ");
}

function objType(s, ind) {
  const req = new Set(s.required ?? []);
  const pad = "  ".repeat(ind + 1);
  const lines = Object.entries(s.properties).map(
    ([k, v]) => `${pad}${prop(k)}${req.has(k) ? "" : "?"}: ${tsType(v, ind + 1)};`,
  );
  return `{\n${lines.join("\n")}\n${"  ".repeat(ind)}}`;
}

// enumSites walks a schema and records every x-extensible-enum location as a path of
// property names ("[]" for array items), resolving $refs to named enum schemas.
function enumSites(s, schemas, path, out, seen) {
  if (!s) return;
  if (s.$ref) {
    const name = refName(s.$ref);
    const target = schemas[name];
    if (target?.enum && target["x-extensible-enum"]) out.push({ path, values: target.enum });
    else if (!seen.has(name)) enumSites(target, schemas, path, out, new Set([...seen, name]));
    return;
  }
  if (s.enum && s["x-extensible-enum"]) {
    out.push({ path, values: s.enum });
    return;
  }
  if (s.items) enumSites(s.items, schemas, [...path, "[]"], out, seen);
  for (const [k, v] of Object.entries(s.properties ?? {})) enumSites(v, schemas, [...path, k], out, seen);
}

function successSchema(op) {
  for (const code of ["200", "201", "202"]) {
    const s = op.responses?.[code]?.content?.["application/json"]?.schema;
    if (s) return s;
  }
  return null;
}

export function generate(spec) {
  const schemas = spec.components?.schemas ?? {};
  const out = [];
  out.push(
    "// GENERATED by tools/gen_client.mjs from api/openapi.yaml. DO NOT EDIT.",
    "// Regenerate: node tools/gen_client.mjs",
    "//",
    "// rule: ARC-I-002",
    "// Responses ignore unknown fields and decode unknown x-extensible-enum values to \"other\",",
    "// which enumLabel renders as 'Other'.",
    "",
    "export const OTHER = \"other\" as const;",
    "",
  );

  out.push("// Schemas (components.schemas).");
  for (const [name, s] of Object.entries(schemas)) {
    if (s.description) out.push(`/** ${String(s.description).replace(/\s+/g, " ").replace(/\*\//g, "* /")} */`);
    out.push(`export type ${name} = ${tsType(s, 0)};`, "");
  }

  out.push("// Known values of every x-extensible-enum schema.");
  out.push("export const extensibleEnums = {");
  for (const [name, s] of Object.entries(schemas)) {
    if (s.enum && s["x-extensible-enum"]) out.push(`  ${name}: ${JSON.stringify(s.enum)},`);
  }
  out.push("} as const;", "");

  out.push("// Extensible-enum sites per response schema, as property paths (\"[]\" = array item).");
  out.push("export interface EnumSite {", "  path: string[];", "  values: readonly string[];", "}", "");
  out.push("export const enumSitesBySchema: Record<string, EnumSite[]> = {");
  for (const [name, s] of Object.entries(schemas)) {
    const sites = [];
    enumSites(s, schemas, [], sites, new Set([name]));
    if (sites.length) out.push(`  ${name}: ${JSON.stringify(sites)},`);
  }
  out.push("};", "");

  const ops = [];
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    for (const m of METHODS) {
      const op = item[m];
      if (!op?.operationId) continue;
      const rs = successSchema(op);
      const sites = [];
      if (rs) enumSites(rs, schemas, [], sites, new Set());
      ops.push({ id: op.operationId, method: m.toUpperCase(), path, sites, rs });
    }
  }

  out.push("// Operations (paths), keyed by operationId.");
  out.push("export const operations: Record<string, { method: string; path: string; sites: EnumSite[] }> = {");
  for (const o of ops) {
    out.push(`  ${o.id}: { method: ${JSON.stringify(o.method)}, path: ${JSON.stringify(o.path)}, sites: ${JSON.stringify(o.sites)} },`);
  }
  out.push("};", "");
  out.push("export type OperationId = keyof OperationResponses;", "");

  out.push("export interface OperationResponses {");
  for (const o of ops) out.push(`  ${o.id}: ${o.rs ? tsType(o.rs, 1) : "void"};`);
  out.push("}", "");

  out.push(RUNTIME);
  return out.join("\n");
}

const RUNTIME = `export interface RequestOptions {
  params?: Record<string, string>;
  query?: Record<string, string | number | boolean | undefined>;
  body?: unknown;
  headers?: Record<string, string>;
  signal?: AbortSignal;
}

export class ApiError extends Error {
  constructor(
    readonly status: number,
    readonly problem: Problem | null,
  ) {
    super(problem ? \`\${status} \${problem.code}: \${problem.title}\` : \`HTTP \${status}\`);
  }
}

export type Fetch = (input: string, init?: RequestInit) => Promise<Response>;

// rule: ARC-I-002
// decodeEnum keeps a known value and maps anything else to OTHER.
export function decodeEnum<T extends string>(values: readonly T[], v: unknown): T | typeof OTHER {
  return typeof v === "string" && (values as readonly string[]).includes(v) ? (v as T) : OTHER;
}

// enumLabel renders an enum value for display; the OTHER sentinel renders as 'Other'.
export function enumLabel(v: string): string {
  if (v === OTHER) return "Other";
  const s = v.replace(/_/g, " ");
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function rewrite(node: unknown, path: string[], values: readonly string[]): unknown {
  if (path.length === 0) return decodeEnum(values, node);
  if (node === null || typeof node !== "object") return node;
  const [head, ...rest] = path;
  if (head === "[]") {
    return Array.isArray(node) ? node.map((x) => rewrite(x, rest, values)) : node;
  }
  const obj = node as Record<string, unknown>;
  if (!(head in obj)) return node;
  return { ...obj, [head]: rewrite(obj[head], rest, values) };
}

// rule: ARC-I-002
// decode applies extensible-enum sites to a parsed response body. Unknown fields pass
// through untouched and unknown enum values become OTHER; it never throws on either.
export function decode<T>(sites: readonly EnumSite[], raw: unknown): T {
  let out: unknown = raw;
  for (const s of sites) out = rewrite(out, s.path, s.values);
  return out as T;
}

// decodeSchema decodes a body of a named components schema, e.g. decodeSchema<Bill>("Bill", raw).
export function decodeSchema<T>(schema: string, raw: unknown): T {
  return decode<T>(enumSitesBySchema[schema] ?? [], raw);
}

export class Client {
  constructor(
    private readonly baseUrl: string,
    private readonly fetchFn: Fetch = (i, init) => fetch(i, init),
  ) {}

  async call<K extends OperationId>(id: K, opts: RequestOptions = {}): Promise<OperationResponses[K]> {
    const op = operations[id];
    let path: string = op.path;
    for (const [k, v] of Object.entries(opts.params ?? {})) path = path.replace(\`{\${k}}\`, encodeURIComponent(v));
    const q = new URLSearchParams();
    for (const [k, v] of Object.entries(opts.query ?? {})) if (v !== undefined) q.set(k, String(v));
    const qs = q.toString();
    const headers: Record<string, string> = { Accept: "application/json", ...(opts.headers ?? {}) };
    if (opts.body !== undefined) headers["Content-Type"] = "application/json";
    const res = await this.fetchFn(this.baseUrl + path + (qs ? "?" + qs : ""), {
      method: op.method,
      headers,
      body: opts.body === undefined ? undefined : JSON.stringify(opts.body),
      signal: opts.signal,
      credentials: "include",
    });
    if (!res.ok) {
      let problem: Problem | null = null;
      try {
        problem = (await res.json()) as Problem;
      } catch {
        problem = null;
      }
      throw new ApiError(res.status, problem);
    }
    if (res.status === 204) return undefined as OperationResponses[K];
    const text = await res.text();
    return decode<OperationResponses[K]>(op.sites, text ? JSON.parse(text) : undefined);
  }
}
`;

// readClient returns the committed client text.
export function readClient() {
  return readFileSync(outPath, "utf8");
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const text = generate(loadSpec());
  if (process.argv.includes("--check")) {
    const cur = readClient();
    if (cur !== text) {
      console.error("web/src/app/api/client.ts is stale; run: node tools/gen_client.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(outPath, text);
  }
}
