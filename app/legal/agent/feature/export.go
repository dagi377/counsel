// Tool-use features run on Paploo in production: each one ships as a skill of Counsel's
// Paploo plugin. The checked-in skills are regenerated from the app's definitions
// (app/legal/agent/featureset, which can import the feature packages) with
//
//	go generate ./app/legal/agent/featureset
//
// and a test there fails while they differ.

// SkillsDir is where the plugin's skills live, relative to the repository root.
const SkillsDir = "paploo/counsel-plugin/skills"

// SkillFile is the file name of one skill inside its directory.
const SkillFile = "SKILL.md"

// generatedMark is the line every generated skill carries; a skill directory without it is
// hand-written and left alone.
const generatedMark = "<!-- Code generated by go generate (app/legal/agent/feature); DO NOT EDIT. -->"

// ErrSkillsStale: the checked-in skills differ from the app's tool-use definitions.
var ErrSkillsStale = errors.New("feature: plugin skills differ from the definitions")

// TurnPrefix is the head of every turn's prompt on the Paploo path: the feature id and the
// run id, so test/fakes/llm routes by feature without seeing client content (mocks.md sec. 9).
func TurnPrefix(featureID, runID string) string {
	return Preamble(featureID) + "run: " + runID + "\n"
}

// ToolUse reports whether d runs as an agent with tools, the kind that ships as a skill.
func (d Def) ToolUse() bool {
	return d.Kind == "" || d.Kind == ai.KindToolUse
}

var nonSlug = regexp.MustCompile(`[^a-z0-9]+`)

// SkillName is the directory name of d's skill: its lower-case id and name, "f-tim-01-...".
func SkillName(d Def) string {
	slug := strings.Trim(nonSlug.ReplaceAllString(strings.ToLower(d.ID+" "+d.Name), "-"), "-")
	return slug
}

// Skill renders d's SKILL.md: front matter, the turn prefix, the tool list and the system
// prompt. d must be a valid tool-use definition.
func Skill(d Def) ([]byte, error) {
	if !d.ToolUse() {
		return nil, fmt.Errorf("feature %s: kind %s is not tool use: %w", d.ID, d.Kind, ErrBadDef)
	}
	spec, err := d.Spec()
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	desc := fmt.Sprintf("Counsel feature %s (%s).", d.ID, d.Name)
	if d.Trigger != "" {
		desc += " Runs on: " + d.Trigger + "."
	}
	fmt.Fprintf(&b, "---\nname: %s\ndescription: %q\n---\n%s\n\n", SkillName(d), desc, generatedMark)
	fmt.Fprintf(&b, "# %s %s\n\n", d.ID, d.Name)
	// rule: ARC-I-046
	// The skill reaches Counsel only through its tools on the app-API connection; it names no
	// other connector, and every write tool opens a Counsel gate.
	b.WriteString("Start the prompt of every turn with these two lines, before any other text:\n\n")
	for _, l := range strings.Split(strings.TrimSuffix(TurnPrefix(d.ID, "<run id>"), "\n"), "\n") {
		fmt.Fprintf(&b, "    %s\n", l)
	}
	b.WriteString("\n`<run id>` is the Counsel agent run this turn belongs to. Never put client content in these lines.\n\n")
	b.WriteString("## Tools\n\nCall only these Counsel tools, through the Counsel app-API connection:\n\n")
	for _, name := range d.Tools {
		t, err := schemas.ByName(name)
		if err != nil {
			return nil, fmt.Errorf("feature %s: %w", d.ID, err)
		}
		fmt.Fprintf(&b, "- `%s` (%s)\n", t.Name, t.Kind)
	}
	if len(d.GateKinds) > 0 {
		b.WriteString("\n## Gates\n\nA write tool only opens one of these gates; a person decides it:\n\n")
		for _, k := range d.GateKinds {
			fmt.Fprintf(&b, "- `%s`\n", k)
		}
	}
	b.WriteString("\n## Prompt\n\n")
	b.WriteString(strings.TrimRight(spec.System, "\n"))
	b.WriteString("\n")
	return b.Bytes(), nil
}

// Skills renders the skill of every tool-use definition in s, keyed by skill name.
func Skills(s *Set) (map[string][]byte, error) {
	out := map[string][]byte{}
	for _, d := range s.All() {
		if !d.ToolUse() {
			continue
		}
		body, err := Skill(d)
		if err != nil {
			return nil, err
		}
		name := SkillName(d)
		if _, dup := out[name]; dup {
			return nil, fmt.Errorf("feature %s: skill name %s repeated: %w", d.ID, name, ErrBadDef)
		}
		out[name] = body
	}
	return out, nil
}

// generated lists the generated skill directories under fsys (rooted at the skills dir).
func generated(fsys fs.FS) (map[string][]byte, error) {
	out := map[string][]byte{}
	entries, err := fs.ReadDir(fsys, ".")
	if errors.Is(err, fs.ErrNotExist) {
		return out, nil
	}
	if err != nil {
		return nil, fmt.Errorf("skills: %w", err)
	}
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		b, err := fs.ReadFile(fsys, path.Join(e.Name(), SkillFile))
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, fmt.Errorf("skill %s: %w", e.Name(), err)
		}
		if bytes.Contains(b, []byte(generatedMark)) {
			out[e.Name()] = b
		}
	}
	return out, nil
}

// CheckSkills returns ErrSkillsStale, naming each skill, when the generated skills in fsys
// (rooted at the skills dir) differ from the tool-use definitions in s.
func CheckSkills(s *Set, fsys fs.FS) error {
	want, err := Skills(s)
	if err != nil {
		return err
	}
	have, err := generated(fsys)
	if err != nil {
		return err
	}
	var diff []string
	for name, body := range want {
		got, ok := have[name]
		switch {
		case !ok:
			diff = append(diff, name+" missing")
		case !bytes.Equal(got, body):
			diff = append(diff, name+" changed")
		}
	}
	for name := range have {
		if _, ok := want[name]; !ok {
			diff = append(diff, name+" has no definition")
		}
	}
	if len(diff) > 0 {
		slices.Sort(diff)
		return fmt.Errorf("%s (run go generate ./app/legal/agent/featureset): %w", strings.Join(diff, ", "), ErrSkillsStale)
	}
	return nil
}

// ExportSkills writes one SKILL.md per tool-use definition in s under dir and removes the
// generated skills that no longer have a definition. Hand-written skills are kept.
func ExportSkills(s *Set, dir string) error {
	want, err := Skills(s)
	if err != nil {
		return err
	}
	have, err := generated(os.DirFS(dir))
	if err != nil {
		return err
	}
	for name := range have {
		if _, ok := want[name]; !ok {
			if err := os.RemoveAll(filepath.Join(dir, name)); err != nil {
				return fmt.Errorf("skill %s: %w", name, err)
			}
		}
	}
	for name, body := range want {
		if err := os.MkdirAll(filepath.Join(dir, name), 0o755); err != nil {
			return fmt.Errorf("skill %s: %w", name, err)
		}
		if err := os.WriteFile(filepath.Join(dir, name, SkillFile), body, 0o644); err != nil {
			return fmt.Errorf("skill %s: %w", name, err)
		}
	}
	return nil
}
